import { useId, useRef, useState } from "react";
import { useCloseOnOutside } from "../hooks/useCloseOnOutside.js";

export function AiDisclaimer(): JSX.Element {
  const [open, setOpen] = useState(false);
  const disclaimerRef = useRef<HTMLDivElement>(null);
  const tooltipId = useId();
  useCloseOnOutside(disclaimerRef, open, () => setOpen(false));

  return (
    <div className="ai-disclaimer" ref={disclaimerRef} aria-live="off">
      This chat{" "}
      <button
        className="ai-disclaimer-term"
        type="button"
        aria-describedby={tooltipId}
        onBlur={() => setOpen(false)}
        onMouseDown={(event) => event.preventDefault()}
        onClick={() => setOpen(!open)}
      >
        uses AI
      </button>
      .
      <div
        id={tooltipId}
        className={`ai-disclaimer-tooltip ${open ? "open" : ""}`}
        role="tooltip"
      >
        Replies are generated by AI and can sometimes be inaccurate or
        incomplete. Double-check anything important.
      </div>
    </div>
  );
}
